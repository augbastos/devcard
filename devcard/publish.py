"""Render the card and publish it to an orphan branch of a repository you own.

    local SQLite ─ aggregate ─> machines/<id>.json ─┐
                                 (other machines') ─┴─ merge ─ render ─> card.svg, card-dark.svg
                                                                          └─> one commit on `devcard-data`

The branch holds one commit, always: each publish builds a fresh root commit
from (this machine's new aggregate + every other machine's file as found) and
pushes it with --force-with-lease against the commit it read. If another
machine published in between, the lease fails, and the whole step is redone on
top of what it pushed — so no machine can drop another's file, and the branch
does not grow a commit per publish.

Everything is done with git plumbing in a private bare repository under
~/.claude/devcard/publish/. Nothing touches a working tree of yours, and git's
own identity settings are not used: a commit made with an unset identity would
carry `user@hostname`, and the card's privacy promise covers machine names too.
"""
import base64
import json
import os
import re
import shutil
import subprocess
import time
import warnings

from . import config, data, usage
from ._hook import lib
from .render import render
from .themes import theme_pair

BRANCH = "devcard-data"
REF = f"refs/heads/{BRANCH}"
TRACKING_REF = f"refs/remotes/origin/{BRANCH}"
MIN_INTERVAL = 15 * 60
LOCK_STALE_SECONDS = 600
PUSH_ATTEMPTS = 3
AVATAR_TTL = 86400
AVATAR_FAILURE_TTL = 3600
AVATAR_MAX_BYTES = 256 * 1024
BRANCH_MARKER = b'{"format": 1}\n'
MACHINE_PATH_RE = re.compile(r"machines/[A-Za-z0-9_-]{1,64}\.json\Z")

# What git exports to a hook so that commands find *that* repository
# (`git rev-parse --local-env-vars`, plus the -c passthrough). Inherited by a
# publish started from the post-commit hook, they would point every command
# below at the user's project instead of the private bare repository.
REPO_ENV_VARS = (
    "GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_CONFIG", "GIT_CONFIG_PARAMETERS", "GIT_CONFIG_COUNT",
    "GIT_OBJECT_DIRECTORY", "GIT_DIR", "GIT_WORK_TREE", "GIT_IMPLICIT_WORK_TREE", "GIT_GRAFT_FILE",
    "GIT_INDEX_FILE", "GIT_NO_REPLACE_OBJECTS", "GIT_REPLACE_REF_BASE", "GIT_PREFIX",
    "GIT_SHALLOW_FILE", "GIT_COMMON_DIR", "GIT_NAMESPACE",
)

AUTHOR_ENV = {
    "GIT_AUTHOR_NAME": "devcard",
    "GIT_AUTHOR_EMAIL": "devcard@devcard.invalid",
    "GIT_COMMITTER_NAME": "devcard",
    "GIT_COMMITTER_EMAIL": "devcard@devcard.invalid",
}

BRANCH_README = """# devcard-data

Generated by [devcard](https://github.com/augbastos/devcard). Every publish
replaces this branch with a single commit, so do not edit it by hand.

| File | What |
|---|---|
| `card.svg`, `card-dark.svg` | The card, for light and dark GitHub themes |
| `machines/<id>.json` | One machine's totals: languages, counts, lines per day. The id is random. |

No file name, path, project name or code is in any of these files.
"""


class PublishError(Exception):
    """A publish that could not complete. The message is safe to print."""


# -- git ----------------------------------------------------------------------

def _credential_args(url):
    """Let git authenticate to GitHub through `gh`, for this command only.

    This is what `gh auth setup-git` writes into your global config; passing it
    with -c instead leaves that config alone. The empty value first clears any
    other helper, so a stale credential manager cannot answer instead.
    """
    if not url.startswith("https://github.com/"):
        return []
    gh = shutil.which("gh")
    if not gh:
        return []
    gh = gh.replace("\\", "/")
    return [
        "-c", "credential.https://github.com.helper=",
        "-c", f'credential.https://github.com.helper=!"{gh}" auth git-credential',
    ]


class _Repo:
    """The private bare repository publishing goes through."""

    def __init__(self, path, url):
        self.path = path
        self.url = url
        self.cred = _credential_args(url)

    def git(self, *args, stdin=None, env=None, check=True):
        base = {k: v for k, v in os.environ.items()
                if k not in REPO_ENV_VARS and not k.startswith("GIT_CONFIG_")}
        # Publishing runs in the background: a credential prompt would hang there.
        base["GIT_TERMINAL_PROMPT"] = "0"
        base["GIT_CONFIG_NOSYSTEM"] = "1"
        base["GIT_CONFIG_GLOBAL"] = os.devnull
        try:
            proc = subprocess.run(
                ["git", "-c", "core.hooksPath=", "-c", "commit.gpgSign=false",
                 "-c", "tag.gpgSign=false", *self.cred, "-C", self.path, *args],
                input=stdin, capture_output=True, env={**base, **(env or {})},
                timeout=120,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise PublishError(f"git {args[0]} failed: {exc}") from exc
        if check and proc.returncode != 0:
            raise PublishError(f"git {args[0]} failed: {proc.stderr.decode('utf-8', 'replace').strip()}")
        return proc

    def out(self, *args, **kwargs):
        return self.git(*args, **kwargs).stdout.decode("utf-8", "replace").strip()

    def ensure(self):
        if not os.path.isdir(os.path.join(self.path, "objects")):
            os.makedirs(self.path, exist_ok=True)
            self.git("init", "-q", "--bare")
        if self.git("remote", "get-url", "origin", check=False).returncode == 0:
            self.git("remote", "set-url", "origin", self.url)
        else:
            self.git("remote", "add", "origin", self.url)
        # The branch is always one root commit, so shallow fetches save nothing, and
        # a stale shallow list makes git reject a later identical commit (same tree,
        # same second) with "shallow update not allowed". Older clones carry one.
        shallow = os.path.join(self.path, "shallow")
        if os.path.exists(shallow):
            os.remove(shallow)

    def fetch_head(self):
        """The branch's current commit on the remote (fetched), or None if it does not exist yet."""
        listing = self.git("ls-remote", "origin", REF, check=False)
        if listing.returncode != 0:
            detail = listing.stderr.decode("utf-8", "replace").strip()
            raise PublishError(f"cannot reach the repository ({detail})")
        if not listing.stdout.strip():
            return None
        self.git("fetch", "-q", "origin", f"+{REF}:{TRACKING_REF}")
        return self.out("rev-parse", TRACKING_REF)

    def machine_files(self, commit):
        if commit is None:
            return {}
        names = self.out("ls-tree", "-r", "--name-only", commit, "--", "machines").splitlines()
        return {
            name: self.git("cat-file", "blob", f"{commit}:{name}").stdout
            for name in names
            if name.startswith("machines/") and name.endswith(".json")
        }

    def tree_of(self, commit):
        return None if commit is None else self.out("rev-parse", f"{commit}^{{tree}}")

    def validate_target(self, commit):
        """Refuse default branches, unmarked trees and history we cannot replace."""
        head = self.out("ls-remote", "--symref", "origin", "HEAD")
        if f"ref: {REF}\tHEAD" in head.splitlines():
            raise PublishError(f"refusing to publish: {BRANCH} is the repository's default branch")
        if commit is None:
            return

        # Inspect the raw commit: shallow fetches hide parents from rev-list.
        headers = self.out("cat-file", "-p", commit).split("\n\n", 1)[0].splitlines()
        if any(line.startswith("parent ") for line in headers):
            raise PublishError(f"refusing to publish: {BRANCH} must contain a single root commit")

        entries = self.git("ls-tree", "-r", "-z", commit).stdout.split(b"\0")
        names = set()
        for entry in filter(None, entries):
            meta, name = entry.split(b"\t", 1)
            mode, kind, _oid = meta.split()
            name = name.decode("utf-8", "replace")
            if (mode != b"100644" or kind != b"blob"
                    or (name not in (".devcard", "README.md", "card.svg", "card-dark.svg")
                        and not MACHINE_PATH_RE.fullmatch(name))):
                raise PublishError(f"refusing to publish: {BRANCH} is not owned by devcard (unexpected layout)")
            names.add(name)
        if not {".devcard", "card.svg", "card-dark.svg"} <= names:
            raise PublishError(f"refusing to publish: {BRANCH} is not owned by devcard (missing marker or cards)")
        try:
            marker = json.loads(self.git("cat-file", "blob", f"{commit}:.devcard").stdout)
            valid = (isinstance(marker, dict) and set(marker) == {"format"}
                     and type(marker["format"]) is int and marker["format"] == 1)
        except ValueError:
            valid = False
        if not valid:
            raise PublishError(f"refusing to publish: {BRANCH} is not owned by devcard (unsupported marker)")
        if "README.md" in names and self.git("cat-file", "blob", f"{commit}:README.md").stdout != BRANCH_README.encode("utf-8"):
            raise PublishError(f"refusing to publish: {BRANCH} is not owned by devcard (foreign README)")

    def write_tree(self, files):
        index = os.path.join(self.path, "devcard-index")
        if os.path.exists(index):
            os.remove(index)
        env = {"GIT_INDEX_FILE": index}
        entries = []
        for name in sorted(files):
            blob = self.out("hash-object", "-w", "--stdin", stdin=files[name])
            entries.append(f"100644 {blob}\t{name}\n")
        self.git("update-index", "--index-info", stdin="".join(entries).encode("utf-8"), env=env)
        tree = self.out("write-tree", env=env)
        os.remove(index)
        return tree

    def commit(self, tree, now):
        stamp = f"{int(now)} +0000"
        env = {**AUTHOR_ENV, "GIT_AUTHOR_DATE": stamp, "GIT_COMMITTER_DATE": stamp}
        return self.out("commit-tree", tree, "-m", "devcard: update card", env=env)

    def push(self, commit, expected):
        lease = f"--force-with-lease={REF}:{expected or ''}"
        proc = self.git("push", "-q", lease, "origin", f"{commit}:{REF}", check=False)
        return proc.returncode == 0, proc.stderr.decode("utf-8", "replace").strip()


# -- state, lock, avatar -------------------------------------------------------

def _read_json(path):
    try:
        with open(path, encoding="utf-8") as f:
            value = json.load(f)
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def _write_json(path, value):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(value, f)
    os.replace(tmp, path)


class _Lock:
    """One publish at a time per machine; the hooks can fire several at once."""

    def __init__(self, path):
        self.path = path
        self.held = False

    def __enter__(self):
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        for _ in range(2):
            try:
                os.close(os.open(self.path, os.O_CREAT | os.O_EXCL | os.O_WRONLY))
                self.held = True
                return self
            except FileExistsError:
                try:
                    if time.time() - os.stat(self.path).st_mtime > LOCK_STALE_SECONDS:
                        os.remove(self.path)  # a publish that died; take over
                        continue
                except OSError:
                    continue
                break
        return self

    def __exit__(self, *exc):
        if self.held:
            try:
                os.remove(self.path)
            except OSError:
                pass


def fetch_avatar(user, now=None):
    """The GitHub avatar as a data: URI, cached a day. None on any failure."""
    now = time.time() if now is None else now
    path = config.avatar_cache_path()
    cached = _read_json(path)
    if cached.get("user") == user:
        ttl = AVATAR_TTL if cached.get("data_uri") else AVATAR_FAILURE_TTL
        if 0 <= now - cached.get("fetched_at", 0) < ttl:
            return cached.get("data_uri")
    data_uri = None
    try:
        import urllib.request

        req = urllib.request.Request(
            f"https://github.com/{user}.png?size=96", headers={"User-Agent": "devcard/2"}
        )
        with urllib.request.urlopen(req, timeout=10) as resp:
            ctype = resp.headers.get("Content-Type", "image/png").split(";")[0].strip()
            body = resp.read(AVATAR_MAX_BYTES + 1)
        if ctype.startswith("image/") and len(body) <= AVATAR_MAX_BYTES:
            data_uri = f"data:{ctype};base64,{base64.b64encode(body).decode('ascii')}"
    except Exception:
        data_uri = None
    try:
        _write_json(path, {"user": user, "fetched_at": int(now), "data_uri": data_uri})
    except OSError:
        pass
    return data_uri


# -- the card -------------------------------------------------------------------

def local_aggregate(cfg, now, repo_count_fn=None):
    """This machine's aggregate, from the hook's database."""
    conn = lib.init_db()
    try:
        usage.scan_local(cfg, conn)
        consent = config.consents(cfg)
        count = None
        if consent["repo_count"]:
            count = (repo_count_fn(conn) if repo_count_fn else
                     lib.repo_count(conn, include_private=consent["repo_count_private"]))
        agg = data.aggregate(conn, now, tz=cfg.get("timezone") or None, repo_count=count or 0,
                             consent=consent, repo_count_private=consent["repo_count_private"])
        if count is None:
            agg.pop("repo_count", None)
            agg.pop("repo_count_private", None)
        return agg
    finally:
        conn.close()


def render_files(cfg, aggregates, now, avatar=None):
    """{name: bytes} for the two card files, from any number of machine aggregates."""
    card = data.card_data(
        data.merge([data.consented(agg, config.consents(cfg)) for agg in aggregates], now=now),
        cfg["github_user"], now, locale=cfg["lang"],
        tz=cfg.get("timezone") or None, avatar=avatar,
        badges=[b for b in cfg.get("badges") or [] if isinstance(b, dict) and "label" in b],
        pins=[{"repo": p["repo"], "note": p.get("note"), "stars": None}
              for p in cfg.get("pins") or [] if isinstance(p, dict) and "repo" in p],
        card=cfg.get("card"),
    )
    light, dark = theme_pair(cfg["theme"])
    return {
        "card.svg": render(card, light, cfg["lang"], cfg["layout"], now=now, static=True).encode("utf-8"),
        "card-dark.svg": render(card, dark, cfg["lang"], cfg["layout"], now=now, static=True).encode("utf-8"),
    }


def encode_aggregate(agg):
    return (json.dumps(agg, indent=1, sort_keys=True) + "\n").encode("utf-8")


def _same_except_time(a, b):
    strip = lambda d: {k: v for k, v in d.items() if k != "updated_at"}  # noqa: E731
    return strip(a) == strip(b)


def render_local(cfg, out_dir, now=None, repo_count_fn=None, avatar_fn=None):
    """`devcard render`: this machine's card, written to `out_dir`. Returns the paths."""
    now = int(time.time() if now is None else now)
    agg = local_aggregate(cfg, now, repo_count_fn)
    avatar = (avatar_fn or fetch_avatar)(cfg["github_user"]) if cfg.get("avatar") else None
    os.makedirs(out_dir, exist_ok=True)
    paths = []
    for name, body in render_files(cfg, [agg], now, avatar).items():
        path = os.path.join(out_dir, name)
        with open(path, "wb") as f:
            f.write(body)
        paths.append(path)
    return paths


def publish(cfg, now=None, force=False, repo_count_fn=None, avatar_fn=None):
    """Publish this machine's numbers and the merged card. Returns a short status.

    "skipped" — published less than 15 minutes ago (use force to override);
    "unchanged" — the branch already holds exactly this; "published" — pushed.
    Raises PublishError when it cannot complete.
    """
    now = int(time.time() if now is None else now)
    if not cfg or not cfg.get("repo") or not cfg.get("github_user"):
        raise PublishError("not configured — run `devcard init` first")
    if not config.has_consent(cfg):
        raise PublishError("no publication consent — run `devcard privacy --grant <category>` or `devcard init --consent <categories>`")

    state = _read_json(config.state_path())
    if not force and 0 <= now - state.get("last_check", 0) < MIN_INTERVAL:
        return "skipped"

    with _Lock(config.lock_path()) as lock:
        if not lock.held:
            return "skipped"
        saved = config.load()
        if saved and saved.get("repo") == cfg["repo"] and config.remote_url(saved) == config.remote_url(cfg):
            current = config.consents(saved)
            cfg = {**cfg, "consent": {key: value and current[key] for key, value in config.consents(cfg).items()}}
            if not config.has_consent(cfg):
                raise PublishError("publication consent was revoked; run `devcard privacy` to review")
        state = _read_json(config.state_path())
        if not force and 0 <= now - state.get("last_check", 0) < MIN_INTERVAL:
            return "skipped"
        state["last_check"] = now
        _write_json(config.state_path(), state)

        # Aggregate first: opening a database that does not exist yet retires the
        # machine id (it names the rowids of one events.db — see init_db), so an
        # id read before that would be gone by the next publish.
        agg = local_aggregate(cfg, now, repo_count_fn)
        source = lib.source_id()
        if not source:
            raise PublishError(f"no machine id could be created at {lib.SOURCE_ID_PATH}")
        own = f"machines/{source}.json"
        avatar = (avatar_fn or fetch_avatar)(cfg["github_user"]) if cfg.get("avatar") else None

        repo = _Repo(os.path.join(config.publish_dir(), cfg["repo"].replace("/", "__")), config.remote_url(cfg))
        repo.ensure()
        detail = ""
        for _ in range(PUSH_ATTEMPTS):
            head = repo.fetch_head()
            repo.validate_target(head)
            files = repo.machine_files(head)
            # A revoke applies to every machine on this account, including old
            # files. The same allowlist builds local JSON and scrubs carried files.
            for name, body in list(files.items()):
                try:
                    previous_agg = json.loads(body)
                    data._validate_aggregate(previous_agg, now)
                    filtered = data.consented(previous_agg, config.consents(cfg))
                    if filtered != previous_agg:
                        files[name] = encode_aggregate(filtered)
                except (ValueError, RecursionError):
                    warnings.warn("Skipping invalid machine aggregate: malformed or unsupported JSON", RuntimeWarning, stacklevel=2)
                    del files[name]
            previous = files.get(own)
            if previous:
                try:
                    old = json.loads(previous)
                    data._validate_aggregate(old, now)
                    if _same_except_time(old, agg) and "updated_at" in old and "updated_at" in agg:
                        agg["updated_at"] = old["updated_at"]
                except (ValueError, RecursionError):
                    warnings.warn("Skipping invalid machine aggregate: previous local file", RuntimeWarning, stacklevel=2)
            files[own] = encode_aggregate(agg)
            aggregates = []
            for body in files.values():
                try:
                    aggregates.append(json.loads(body))
                except (ValueError, RecursionError):
                    warnings.warn("Skipping invalid machine aggregate: malformed JSON", RuntimeWarning, stacklevel=2)
                    continue  # one damaged file must not take the card down
            files.update(render_files(cfg, aggregates, now, avatar))
            files["README.md"] = BRANCH_README.encode("utf-8")
            files[".devcard"] = BRANCH_MARKER

            tree = repo.write_tree(files)
            if tree == repo.tree_of(head):
                state["published_consent"] = config.consents(cfg)
                _write_json(config.state_path(), state)
                return "unchanged"
            ok, detail = repo.push(repo.commit(tree, now), head)
            if ok:
                state["last_push"] = now
                state["published_consent"] = config.consents(cfg)
                _write_json(config.state_path(), state)
                return "published"
        raise PublishError(f"push rejected {PUSH_ATTEMPTS} times ({detail})")


def auto(spawn=True):
    """The hooks' entry point: publish if configured and due. Never raises.

    A publish skipped by the debounce leaves a waiter behind (see when_due), so
    the last edits of a session are published when the window closes instead
    of whenever the next session starts.
    """
    try:
        cfg = config.load()
        if not cfg or not cfg.get("repo"):
            return None
        if not config.has_consent(cfg):
            lib.log_consent_notice()
            return None
        status = publish(cfg)
        if status == "skipped" and spawn:
            _spawn_waiter()
        return status
    except PublishError as exc:
        lib._log_throttled("publish-failure", f"devcard publish: {exc}")
    except Exception as exc:
        lib.log_error(f"devcard publish failed: {exc}")
    return None


def unpublish(cfg):
    """Disable automatic publication and remove only a verified devcard-owned branch."""
    if not cfg or not cfg.get("repo"):
        raise PublishError("not configured — run `devcard init` first")
    cfg = {**cfg, "consent": dict(config.NO_CONSENT)}
    config.save(cfg)
    with _Lock(config.lock_path()) as lock:
        if not lock.held:
            raise PublishError("publication is busy; retry `devcard unpublish`")
        repo = _Repo(os.path.join(config.publish_dir(), cfg["repo"].replace("/", "__")), config.remote_url(cfg))
        repo.ensure()
        for _ in range(PUSH_ATTEMPTS):
            head = repo.fetch_head()
            repo.validate_target(head)
            if head is None:
                _write_json(config.state_path(), {})
                return "already unpublished"
            ok, detail = repo.push("", head)
            if ok:
                _write_json(config.state_path(), {})
                return "unpublished"
        raise PublishError(f"could not remove {BRANCH} after {PUSH_ATTEMPTS} attempts ({detail})")


def _waiter_fresh(marker):
    try:
        return time.time() - os.stat(marker).st_mtime < MIN_INTERVAL + 300
    except OSError:
        return False


def _spawn_waiter():
    """Start `devcard publish --when-due` detached, unless one is already waiting."""
    if _waiter_fresh(config.pending_path()):
        return
    import sys

    flags = 0
    if os.name == "nt":
        flags = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP
    # The parent of this package: the repository root in a checkout (so -m finds
    # devcard/), site-packages' parent under pipx, where site finds it anyway.
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    subprocess.Popen(
        [sys.executable, "-m", "devcard", "publish", "--when-due"],
        cwd=root, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        close_fds=True, creationflags=flags,
    )


def when_due(sleep=time.sleep, clock=time.time, attempts=4):
    """Sleep until the debounce window closes, then publish. One waiter per machine.

    The trailing edge of the debounce: hooks fire on activity, so without this
    the edits made in a session's last 15 minutes would wait for the next
    session. A publish that is skipped again (another check got in first)
    waits for that one's window, a bounded number of times.
    """
    marker = config.pending_path()
    os.makedirs(os.path.dirname(marker), exist_ok=True)
    try:
        os.close(os.open(marker, os.O_CREAT | os.O_EXCL | os.O_WRONLY))
    except FileExistsError:
        if _waiter_fresh(marker):
            return "waiting"
        os.utime(marker)  # a waiter that died; take over
    try:
        status = "skipped"
        for _ in range(attempts):
            last = _read_json(config.state_path()).get("last_check", 0)
            wait = last + MIN_INTERVAL - clock()
            if wait > 0:
                sleep(wait + 1)
            status = auto(spawn=False)
            if status != "skipped":
                return status
        return status
    finally:
        try:
            os.remove(marker)
        except OSError:
            pass
